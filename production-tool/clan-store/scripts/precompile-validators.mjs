// Precompile the contract validators with ajv's standalone code, so the page and the store Worker
// validate with no `new Function` (owner, 2026-11-24: "Okay go with ajv fix"; the CSP stays strict:
// no 'unsafe-eval'). The browser-side check stays: the same schemas, the same ajv options
// (allErrors, strict false, ajv-formats), compiled here instead of at runtime.
//
// Writes src/validators.gen.js, which is committed and shipped as is (the Dockerfile copies it). Run after a
// contract change: `npm run validators`. It is deliberately NOT part of `npm run build`: CI and check.sh build
// before they test, so a build that regenerated it hid a stale file (UAT 2026-11-26: brand_clans refused).
// test/validators.test.ts fails while the committed file is stale.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = join(here, '..')
const require = createRequire(join(pkg, 'package.json'))
const Ajv2020 = require('ajv/dist/2020').default
const standalone = require('ajv/dist/standalone').default
const addFormats = require('ajv-formats').default

const contracts = join(pkg, '..', 'contracts')
const schema = (name) => JSON.parse(readFileSync(join(contracts, `${name}.schema.json`), 'utf8'))

/** The exported validators and the schema each one is: what validate.ts and bus/local.ts compiled at runtime. */
export const EXPORTS = {
  validateDocument: 'https://napkin.ie/production-tool/contracts/document.schema.json',
  validatePatchBatch: 'https://napkin.ie/production-tool/contracts/patch.schema.json#/$defs/PatchBatch',
}

/** The generated module's source. */
export function generate() {
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true, lines: false } })
  addFormats(ajv)
  for (const n of ['common', 'director', 'patch', 'document']) ajv.addSchema(schema(n))
  for (const [name, ref] of Object.entries(EXPORTS)) {
    if (!ajv.getSchema(ref)) throw new Error(`${name}: no schema at ${ref}`)
  }
  const code = standalone(ajv, EXPORTS)
  // ajv's standalone output still require()s its small runtime helpers (equal, ucs2length, the formats).
  // esbuild bundles them in, so the module has no imports: no CommonJS interop for the page, the Worker
  // or the tests to disagree on.
  const bundled = require('esbuild').buildSync({
    stdin: { contents: code, resolveDir: pkg, sourcefile: 'validators.js', loader: 'js' },
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2020',
    mainFields: ['main'], write: false, legalComments: 'none', logLevel: 'silent', absWorkingDir: pkg,
  }).outputFiles[0].text
  // (ajv tags each helper with its source as a string, `.code = 'require("…")'`: a string, not a call)
  if (/(^|[^'"\w.])require\(|new Function|\beval\(|^import /m.test(bundled)) throw new Error('the generated validators must not import, require, eval or new Function')
  return `// Generated by scripts/precompile-validators.mjs (\`npm run validators\`). Do not edit.
// The contract validators (document, patch batch), precompiled with ajv standalone: no eval at runtime.
/* eslint-disable */
// @ts-nocheck
${bundled}`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(pkg, 'src', 'validators.gen.js')
  writeFileSync(out, generate())
  console.log(`wrote ${out}`)
}
