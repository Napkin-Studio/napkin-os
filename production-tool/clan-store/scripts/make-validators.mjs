// Precompile the document and patch-batch validators with ajv standalone code,
// into src/validators.gen.js: ajv's compile() builds validators with
// `new Function`, which a CSP without 'unsafe-eval' blocks (the page bundle and
// the store Worker). The schemas and ajv options are the ones src/validate.ts
// and src/bus/local.ts used to compile at runtime.
//
// Run after a contract change: `npm run validators`. `npm run validators -- --check`
// regenerates in memory and fails if the committed file differs (test/validators.test.ts).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import addFormats from 'ajv-formats'

const here = dirname(fileURLToPath(import.meta.url))
const contracts = join(here, '..', '..', 'contracts')
const out = join(here, '..', 'src', 'validators.gen.js')
const read = name => JSON.parse(readFileSync(join(contracts, name), 'utf8'))
const PATCH_BATCH = 'https://napkin.ie/production-tool/contracts/patch.schema.json#/$defs/PatchBatch'

export function generate() {
  const Ajv = Ajv2020.default ?? Ajv2020
  const formats = addFormats.default ?? addFormats
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } })
  formats(ajv)
  ajv.addSchema(read('common.schema.json'))
  ajv.addSchema(read('director.schema.json'))
  ajv.addSchema(read('patch.schema.json'))
  const document = read('document.schema.json')
  ajv.addSchema(document)
  const code = standaloneCode(ajv, { document: document.$id, patchBatch: PATCH_BATCH })
  // ajv emits require() for its runtime helpers; make them imports (the page
  // bundle, the Worker and vitest are all ESM). Those modules are CommonJS, so
  // unwrap `.default` the way the old runtime code did.
  const code2 = code
    .replace(/require\("ajv\/dist\/runtime\/equal"\)\.default/g, 'unwrap(_equal)')
    .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'unwrap(_ucs2length)')
    .replace(/require\("ajv-formats\/dist\/formats"\)\.fullFormats/g, 'unwrap(_formats).fullFormats')
  if (code2.includes('require(')) throw new Error('make-validators: an unhandled require() in the standalone code')
  const head = [
    '// GENERATED by scripts/make-validators.mjs (npm run validators). Do not edit.',
    '// @ts-nocheck',
    '/* eslint-disable */',
    "import * as _equal from 'ajv/dist/runtime/equal.js'",
    "import * as _ucs2length from 'ajv/dist/runtime/ucs2length.js'",
    "import * as _formats from 'ajv-formats/dist/formats.js'",
    'const unwrap = (m) => { for (let i = 0; i < 3 && m && m.default; i++) m = m.default; return m }',
    '',
  ].join('\n')
  return head + code2
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = generate()
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== code) { console.error('src/validators.gen.js is stale: run npm run validators'); process.exit(1) }
  } else writeFileSync(out, code)
}
