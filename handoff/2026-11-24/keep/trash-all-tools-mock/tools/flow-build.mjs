// Click-through of the real build against the real napkin-web on 5490: move, confirm, toast, Trash page, Restore, Undo,
// the doc menu in a tool, the agency Trash, and the host's own rows (title, tool, who).
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const B = 'http://127.0.0.1:5490'
const b = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome' })
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } })
const p = await ctx.newPage()
p.on('pageerror', e => { console.log('PAGEERR', e.message.slice(0, 300)); process.exitCode = 1 })
await p.goto(B + '/')
assert.ok((await p.request.post(`${B}/api/auth/sign-in`, { data: { username: 'aoife@napkin' } })).ok())
await p.goto(B + '/')
const { tenant } = await (await p.request.get(`${B}/api/session`)).json()
const t = `${B}/api/t/${tenant}`
const j = async (m, path, data) => { const r = await p.request.fetch(t + path, { method: m, ...(data ? { data } : {}) }); assert.ok(r.ok(), `${m} ${path} ${r.status()}`); return r.json().catch(() => ({})) }
const c = await j('POST', '/clients', { name: 'Flowco ' + Date.now() })
const mk = async (app, title) => (await j('POST', '/documents', { app_id: app, title, client_id: c.id })).path
const brief = await mk('ie.napkin.brief-maker', 'Flow brief')
const deck = await mk('ie.napkin.deck-maker', 'Flow deck')
const film = await mk('ie.napkin.production', 'Flow film')
await p.goto(`${B}/#client-${c.id}`)
await p.waitForSelector('[data-testid=client-page]')
assert.equal(await p.locator('[data-testid=trash-link]').count(), 0, 'no Trash link while nothing is deleted')
assert.equal(await p.locator('[data-testid=group-other]').count(), 0, 'Production is not under Other')
assert.match(await p.locator('[data-testid=group-prod]').innerText(), /Flow film/)
// ⋯ -> Move to Trash -> Cancel keeps it, then confirm moves it
await p.getByRole('button', { name: 'Options for Flow deck' }).click()
await p.getByRole('menuitem', { name: /Move to Trash/ }).click()
assert.match(await p.getByTestId('trash-confirm').innerText(), /Move “Flow deck” to Trash\?\s+You can restore it for 30 days\./)
await p.getByRole('button', { name: 'Cancel' }).click()
assert.equal(await p.getByTestId('trash-confirm').count(), 0)
assert.equal(await p.getByText('Flow deck').count() > 0, true)
await p.getByRole('button', { name: 'Options for Flow deck' }).click()
await p.getByRole('menuitem', { name: /Move to Trash/ }).click()
await p.getByTestId('trash-go').click()
await p.waitForSelector('[data-testid=toast]')
assert.match(await p.getByTestId('toast').innerText(), /Moved to Trash/)
await p.waitForFunction(() => !document.body.innerText.includes('Summer') && true)
assert.equal(await p.locator('[data-testid=work-item]', { hasText: 'Flow deck' }).count(), 0, 'gone from its section')
assert.match(await p.getByTestId('trash-link').innerText(), /Trash \(1\)/)
// the host recorded it
const rows = await j('GET', `/trash?client=${c.id}`)
assert.deepEqual(rows.map(r => [r.title, r.app_id, r.client_id, r.by]), [['Flow deck', 'ie.napkin.deck-maker', c.id, 'Aoife']])
// Undo moves it back
await p.getByTestId('toast').getByRole('button', { name: 'Undo' }).click()
await p.locator('[data-testid=work-item]', { hasText: 'Flow deck' }).waitFor()
assert.equal(await p.getByTestId('trash-link').count(), 0)
// move again, open the Trash page, Restore, Undo
await p.getByRole('button', { name: 'Options for Flow deck' }).click()
await p.getByRole('menuitem', { name: /Move to Trash/ }).click(); await p.getByTestId('trash-go').click()
await p.getByTestId('trash-link').waitFor()
await p.getByTestId('trash-link').click()
assert.equal(p.url().endsWith(`#client-${c.id}-trash`), true, p.url())
await p.getByTestId('trash-list').waitFor()
assert.match(await p.getByTestId('trash-item').innerText(), /Flow deck[\s\S]*Deleted today by Aoife · restorable for 30 more days/)
await p.getByRole('button', { name: 'Restore Flow deck' }).click()
await p.getByTestId('trash-empty').waitFor()
await p.getByTestId('toast').filter({ hasText: 'Restored' }).waitFor()
await p.getByTestId('toast').getByRole('button', { name: 'Undo' }).click()
await p.locator('[data-testid=trash-item]').waitFor()
await p.getByRole('button', { name: 'Restore Flow deck' }).click()
await p.getByTestId('trash-back').click()
await p.locator('[data-testid=work-item]', { hasText: 'Flow deck' }).waitFor()
// a Production project moves and restores the same way; the agency Trash lists it with the client's
await p.getByRole('button', { name: 'Options for Flow film' }).click()
await p.getByRole('menuitem', { name: /Move to Trash/ }).click(); await p.getByTestId('trash-go').click()
await p.getByTestId('trash-link').waitFor()
await p.goto(`${B}/#trash`); await p.reload()
await p.getByTestId('trash-page').waitFor()
assert.match(await p.getByTestId('trash-list').innerText(), /Flow film/)
await p.getByRole('button', { name: 'Restore Flow film' }).click()
await p.waitForFunction(() => !document.body.innerText.includes('Flow film'))
// in a tool: the document menu's last item, same confirm, back to the client page
await p.goto(`${B}/#client-${c.id}`); await p.reload()
await p.getByRole('button', { name: 'Flow brief' }).first().click()
await p.waitForSelector('[data-testid=os-bar]'); await p.waitForTimeout(2500)
await p.locator('.tb-name, [aria-haspopup=menu][title^="Document menu"]').first().click()
const items = await p.locator('[data-testid=doc-menu] [role=menuitem]').allInnerTexts()
assert.match(items.at(-1), /Move to Trash/)
await p.getByRole('menuitem', { name: /Move to Trash/ }).click()
assert.match(await p.getByTestId('trash-confirm').innerText(), /Move “Flow brief” to Trash\?/)
await p.getByTestId('trash-go').click()
await p.waitForSelector('[data-testid=client-page]')
assert.equal(await p.locator('[data-testid=work-item]', { hasText: 'Flow brief' }).count(), 0)
assert.deepEqual((await j('GET', `/trash?client=${c.id}`)).map(r => r.title), ['Flow brief'])
console.log('FLOW OK')
await b.close()
